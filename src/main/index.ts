// Main process entry (plan M0-02…07): single instance, app-wide hardening, the three windows, typed IPC,
// the stage overlay with its core, tray and the global toggle hotkey.
import { randomInt } from 'node:crypto';
import { join } from 'node:path';
import { app, globalShortcut, ipcMain, Menu, protocol, screen, session } from 'electron';
import { APP_ID } from '../shared/app.ts';
import { CHANNEL } from '../shared/ipc.ts';
import { WINDOW_ROLES } from '../shared/windows.ts';
import { devSurfaces } from './app/dev-build.ts';
import { isDebugLaunch } from './app/launch-guard.ts';
import { registerLifecycle } from './app/lifecycle.ts';
import { loadRegistry } from './characters/registry.ts';
import { parseArtLineup, selectCharacters } from './characters/selection.ts';
import { createTranslator } from './i18n.ts';
import { IpcRouter } from './ipc/handle.ts';
import { HotkeyService } from './services/hotkeys.ts';
import { TrayService } from './services/tray.ts';
import { StageController, stageWindowOptions } from './stage/controller.ts';
import { APP_ORIGIN, APP_SCHEME_PRIVILEGES, handleAppProtocol } from './windows/app-protocol.ts';
import { WindowManager } from './windows/manager.ts';
import { expectedPageUrl, rendererRoot, trustedDevServerUrl, type PathContext } from './windows/paths.ts';
import { hardenSession, hardenWebContents } from './windows/secure.ts';

/** Global toggle for the character (owner decision D-9). */
const TOGGLE_ACCELERATOR = 'Control+Alt+P';

/** `--name=value` switch, or undefined. */
function argValue(name: string): string | undefined {
  const prefix = `--${name}=`;
  return process.argv.find((arg) => arg.startsWith(prefix))?.slice(prefix.length);
}

function main(): void {
  // Dev-only surfaces need a dev build AND an unpackaged run (app/dev-build.ts); never `app.isPackaged` alone.
  const dev = devSurfaces(app.isPackaged);
  // A production build never runs with a debugger endpoint (rules/security.md).
  if (!dev && isDebugLaunch(process.argv, (name) => app.commandLine.hasSwitch(name))) {
    // exit, not quit: terminate at once so a debugger endpoint has no window while a graceful quit runs.
    app.exit(1);
    return;
  }
  if (!app.requestSingleInstanceLock()) {
    app.quit();
    return;
  }
  // Compat mode (S3, ADR 007): software compositing for GPUs that show black instead of transparency. Before ready.
  if (process.argv.includes('--compat-mode')) app.disableHardwareAcceleration();
  app.setAppUserModelId(APP_ID);
  // Must happen before ready: pages load from app://renderer/<role>/index.html, not file://.
  protocol.registerSchemesAsPrivileged([APP_SCHEME_PRIVILEGES]);

  // Every web contents (including any a compromised page might try to create) gets the navigation guards.
  app.on('web-contents-created', (_event, contents) => {
    hardenWebContents(contents);
    // Dev-only: renderer console (CSP violations, errors) in the terminal.
    if (dev) {
      contents.on('console-message', ({ level, message }) => {
        console.log(`[renderer:${level}] ${message}`);
      });
    }
  });

  const paths: PathContext = {
    mainDir: import.meta.dirname,
    dev,
    devServerUrl: process.env['ELECTRON_RENDERER_URL'],
  };
  // `--perf-seed=<n>` fixes the core seed (pnpm perf); otherwise a fresh one per run. The seed only drives
  // behaviour (activity choice); never use it for anything security-relevant (tokens, ids, crypto).
  const seedArg = Number(argValue('perf-seed'));
  const seed = Number.isInteger(seedArg) ? seedArg : randomInt(0, 2 ** 31);

  // Built-in packs (plan M-ART MA-10/11): generated by `pnpm sprites`; outside app.asar when packaged.
  // Keyed on `app.isPackaged`, not `dev`, on purpose: this is a file layout, not a dev surface. A production build run
  // unpackaged (`electron .` on out/, Playwright `_electron` in M6) has no resources/characters under
  // process.resourcesPath (that is Electron's own dist), so `dev` would leave it with no characters.
  const charactersRoot = app.isPackaged
    ? join(process.resourcesPath, 'characters')
    : join(import.meta.dirname, '..', '..', 'resources', 'characters');
  const registry = loadRegistry(charactersRoot);
  for (const error of registry.errors) console.warn(`[characters] ${error}`);
  // Dev-only art lineup (MA-31): `--art-lineup=<ids>`, up to 4 built-ins side by side; rejected when packaged.
  const artLineup = parseArtLineup(process.argv, registry.packs, !dev);
  if (artLineup.kind === 'error') console.error(`[characters] ${artLineup.error}`);
  const lineup = artLineup.kind === 'lineup' ? artLineup.ids : undefined;
  const selection = selectCharacters({ packs: registry.packs, requested: argValue('character'), lineup });
  if (selection.warning !== undefined) console.warn(`[characters] ${selection.warning}`);
  if (selection.error !== undefined) console.error(`[characters] ${selection.error}`);
  const onStage = selection.characters;

  const displayForStage = () => screen.getPrimaryDisplay();
  const windows = new WindowManager(paths, () => stageWindowOptions(displayForStage()));
  const stage = new StageController({
    stage: () => windows.windowOf('stage'),
    display: displayForStage,
    now: () => Date.now(),
    seed,
    characters: () => onStage,
    animCycle: lineup !== undefined || (dev && process.argv.includes('--anim-cycle')),
  });
  const ipc = new IpcRouter(ipcMain, {
    roleOf: (id) => WINDOW_ROLES.find((role) => windows.windowOf(role)?.webContents.id === id),
    expectedUrl: (role) => expectedPageUrl(role, paths),
  });
  ipc.handle(CHANNEL.ping, ({ nonce }) => ({ nonce, version: app.getVersion() }));
  stage.register(ipc);

  const t = createTranslator('uk');
  const hotkeys = new HotkeyService(globalShortcut);
  let tray: TrayService | undefined;
  let stopSpike: (() => void) | undefined;
  const refreshTray = (): void => {
    tray?.update({
      stageVisible: windows.windowOf('stage')?.isVisible() ?? false,
      layer: stage.layer,
      preset: stage.preset,
      hotkey: hotkeys.status,
    });
  };
  const toggleStage = (): void => {
    const win = windows.windowOf('stage');
    if (win?.isVisible()) win.hide();
    else (win ?? windows.createStage()).showInactive();
    refreshTray();
  };

  void registerLifecycle(app, {
    ready: () => {
      hardenSession(session.defaultSession);
      const devOrigin = trustedDevServerUrl(paths);
      handleAppProtocol(protocol, rendererRoot(paths), {
        root: charactersRoot,
        known: (id, file) => registry.packs.get(id)?.atlas === `sprites/${file}`,
        allowedOrigins: devOrigin === undefined ? [APP_ORIGIN] : [APP_ORIGIN, devOrigin],
      });
      Menu.setApplicationMenu(null); // before any window: no default menu (and its devtools/reload accelerators)
      stage.attach(windows.createStage());

      const onDisplayChanged = (): void => {
        stage.onDisplayChanged();
      };
      screen.on('display-metrics-changed', onDisplayChanged);
      screen.on('display-added', onDisplayChanged);
      screen.on('display-removed', onDisplayChanged);

      tray = new TrayService(
        t,
        {
          toggleStage,
          showChat: () => {
            windows.showChat();
          },
          showSettings: () => {
            windows.showSettings();
          },
          setLayer: (layer) => {
            stage.setLayer(layer);
            refreshTray();
          },
          setPreset: (preset) => {
            stage.setPreset(preset);
            refreshTray();
          },
          nudge: (delta) => {
            stage.nudge(delta);
          },
          quit: () => {
            app.quit();
          },
        },
        onStage[0]?.pack,
        charactersRoot,
      );
      hotkeys.bind(TOGGLE_ACCELERATOR, toggleStage);
      refreshTray();

      // `import.meta.env.DEV` literally here (not only via `dev`): a production build drops this block and its chunks.
      if (import.meta.env.DEV && dev) {
        // Dev-only helpers: open the lazy windows at start; capture the stage over light/dark backdrops.
        if (process.argv.includes('--dev-windows')) {
          windows.showChat();
          windows.showSettings();
        }
        const captureDir = argValue('capture-stage');
        if (captureDir !== undefined) {
          // Loaded on demand: a dev-build-only chunk.
          void import('./dev/capture.ts').then(({ captureStageForDev }) => {
            captureStageForDev(() => windows.windowOf('stage'), captureDir);
          });
        }
        // Spike S4 (plan M1-02): `--desktop-spike=<bench|load|poll|hook> --desktop-spike-out=<dir>`.
        const spikeMode = argValue('desktop-spike');
        const spikeDir = argValue('desktop-spike-out');
        if (spikeMode !== undefined && spikeDir !== undefined) {
          void import('./dev/desktop-spike.ts').then(({ startDesktopSpike, SPIKE_MODES }) => {
            const mode = SPIKE_MODES.find((m) => m === spikeMode);
            if (mode === undefined) {
              console.error(`[spike] unknown mode ${spikeMode}`);
              return;
            }
            const own = (): number[] => {
              const win = windows.windowOf('stage');
              return win ? [Number(win.getNativeWindowHandle().readBigUInt64LE())] : [];
            };
            stopSpike = startDesktopSpike(mode, spikeDir, own);
          });
        }
      }

      return () => {
        stopSpike?.();
        screen.removeListener('display-metrics-changed', onDisplayChanged);
        screen.removeListener('display-added', onDisplayChanged);
        screen.removeListener('display-removed', onDisplayChanged);
        tray?.dispose();
        tray = undefined;
      };
    },
    // A second launch only brings the companion back.
    secondInstance: () => {
      windows.createStage().showInactive();
      refreshTray();
    },
    beforeQuit: () => {
      ipc.dispose();
      windows.destroyAll();
    },
    willQuit: () => {
      hotkeys.dispose();
    },
  });
}

main();
